static int failures = 0;

static void Check(const char* name, const double axes[3][2], const char* const* expected) {
    char got[40][65];
    for (auto& row : got) { std::memset(row, '.', 64); row[64] = 0; }
    for (const view::TripodPixel& p : view::TripodPixels(axes, 423)) {
        const int r = p.y - 360;
        if (r >= 0 && r < 40 && p.x >= 0 && p.x < 64) got[r][p.x] = "RGB"[p.axis];
    }
    for (int r = 0; r < 40; ++r) {
        if (std::strcmp(got[r], expected[r]) != 0) {
            ++failures;
            std::printf("FAIL %s row %d\n  got  %s\n  want %s\n", name, 360 + r, got[r], expected[r]);
        }
    }
}

