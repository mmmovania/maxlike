#pragma once
#include "ui/FrameLayout.h" // ui::Rect
#include <string>
#include <vector>

// The R3.1 main toolbar described as data, plus its layout. No Windows
// dependency (unit-tested in tests/test_toolbar_spec.cpp).
namespace ui::toolbar {

enum class Kind { Button, Separator, Gap, Combo, Edit };

// One choice in a flyout. The button shows the currently chosen one.
struct Alternative {
    std::string  command;
    std::wstring tooltip;
    int icon = -1;
};

struct Item {
    Kind kind = Kind::Button;
    std::string  command;      // Button: command name sent when clicked
    std::wstring tooltip;      // Button: hover text (shown from step 1.4b)
    int  icon = -1;            // Button: index into the icon strip (Icon enum)
    std::vector<Alternative> flyout; // Button: flyout choices (empty = no flyout);
                                     // command/tooltip/icon above start as flyout[0]
    std::string group;         // Button: radio group; "" = plain button
    bool checked = false;      // Button: initially checked (one per group)
    int  width = 0;            // Gap/Combo: width at 100%
    std::wstring text;         // Combo: initially selected entry; Edit: initial text;
                               // Button without icon: its label (e.g. "Animate")
    std::vector<std::wstring> choices; // Combo: the drop-down entries
    bool editable = false;     // Combo: user can type (named selection sets)
    bool toggle = false;       // Button: click flips its checked state
    bool alarm = false;        // Button: red when checked (the Animate button)
    Rect place;                // explicit position at 100% (Config::explicitLayout)
};

// Icon cells in res/toolbar_icons.bmp, left to right (generated by tools/make_icons.py).
enum Icon {
    kIconHelp, kIconUndo, kIconRedo, kIconLink, kIconUnlink, kIconBindWarp,
    kIconSelect, kIconRegionRect, kIconSelectByName, kIconMove, kIconRotate, kIconScale,
    kIconPivotCenter, kIconX, kIconY, kIconZ, kIconXY, kIconIK,
    kIconMirror, kIconArray, kIconAlign, kIconTrackView, kIconSchematic,
    kIconMaterialEditor, kIconRenderScene, kIconQuickRender, kIconRenderLast,
    // flyout alternatives (step 1.4c)
    kIconRegionCircle, kIconRegionFence, kIconScaleNonUniform, kIconScaleSquash,
    kIconPivotSelection, kIconPivotTransform, kIconYZ, kIconZX,
    kIconSnapshot, kIconSpacing, kIconNormalAlign, kIconPlaceHighlight,
    kIconAlignCamera, kIconAlignToView, kIconQuickRenderDraft,
    kIconCount
};

// Measured at 100%.
inline constexpr int kLeft          = 4;   // x of the first item
inline constexpr int kTop           = 4;   // y of buttons and combos
inline constexpr int kButtonWidth   = 32;
inline constexpr int kButtonHeight  = 31;
inline constexpr int kIconSize      = 24;
inline constexpr int kIconOffsetX  = 4;   // icon offset inside a button
inline constexpr int kIconOffsetY  = 3;
inline constexpr int kSeparatorWidth= 6;   // the etched line is at +3 and +4
inline constexpr int kSeparatorTop  = 12;  // line rows 12..27
inline constexpr int kSeparatorHeight = 16;
inline constexpr int kComboHeight   = 21;

// Status-area icon cells in res/status_icons.bmp (16x16), left to right.
enum StatusIcon {
    kSIconDegradeOverride, kSIconWindowCrossing, kSIconAdaptiveDegrade,
    kSIconSnap3D, kSIconSnap25D, kSIconSnap2D, kSIconAngleSnap, kSIconPercentSnap, kSIconSpinnerSnap,
    kSIconGoStart, kSIconPrevFrame, kSIconPlay, kSIconPlaySelected, kSIconNextFrame, kSIconGoEnd,
    kSIconKeyMode, kSIconTimeConfig,
    kSIconZoom, kSIconZoomAll, kSIconZoomExtents, kSIconZoomExtentsSel,
    kSIconZoomExtentsAll, kSIconZoomExtentsAllSel, kSIconRegionZoom, kSIconPan,
    kSIconArcRotate, kSIconArcRotateSel, kSIconArcRotateSub, kSIconMinMax,
    kStatusIconCount
};

enum class IconStrip { Main, Status };

// Everything that differs between the main toolbar and the status-area groups.
struct Config {
    std::vector<Item> items;
    bool explicitLayout = false;   // true: use Item::place; false: left-to-right flow
    IconStrip icons = IconStrip::Main;
    int iconSize = kIconSize;
    int iconOffsetX = kIconOffsetX, iconOffsetY = kIconOffsetY;
    bool frameEdges = true;        // the white/grey columns at the left/right edges
    int flyoutMarkerDx = 0;        // horizontal shift of the flyout notch (measured: +1 in
                                   // the status area relative to the main toolbar)
    bool hasStrips = false;        // follows the tab panel (main toolbar only)
};

const std::vector<Item>& MainToolbarSpec();

Config MainToolbarConfig();
// Bottom-row toggles and snaps, left of the Animate button (status area, step 1.5c).
// Size at 100%: kStatusSnapWidth x kStatusSnapHeight.
Config StatusSnapConfig();
// Animate, playback, key mode, frame field and viewport navigation (step 1.5c).
// Size at 100%: kStatusAnimWidth x 50.
Config StatusAnimConfig();

inline constexpr int kStatusSnapWidth  = 189;
inline constexpr int kStatusSnapHeight = 24;
inline constexpr int kStatusAnimWidth  = 275;

// Rectangles of all items for a toolbar of size w x h.
std::vector<Rect> LayoutItems(const Config& config, int w, int h, unsigned dpi);

// Rectangle of every item (same order as `items`) at `dpi`. Separators and gaps
// span the toolbar height; buttons and combos have their measured size.
std::vector<Rect> LayoutToolbar(const std::vector<Item>& items, int toolbarHeight, unsigned dpi);

} // namespace ui::toolbar
